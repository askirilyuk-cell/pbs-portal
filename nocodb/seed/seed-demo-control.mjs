// ============================================================================
//  Демо-данные контроля качества (Ф.3/Ф.4/Ф.5) для проверки итерации.
//  Создаёт по одному документу каждого вида, привязывает к ПЗ-2026-001.
//  Номера НЕ заполняет — их присвоит assign-control-number.mjs (демо автонумерации).
//  Идемпотентно: по маркеру «(демо)» в опорном поле.
//
//  Запуск:  NC_URL=... NC_TOKEN=... node nocodb/seed/seed-demo-control.mjs
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as nc from '../lib/nocodb-client.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const map = JSON.parse(fs.readFileSync(path.join(__dirname, '..', '.state', 'schema-map.json'), 'utf-8'));
const TID = (key) => map.tables[key].id;
const COL = (key, title) => map.tables[key].columns[title];
const idOf = (r) => r.Id ?? r.id;
const log = (...a) => console.log('  ', ...a);

async function main() {
  await nc.signin();

  const order = (await nc.listRows(TID('orders'))).find((o) => String(o['№ ПЗ']) === 'ПЗ-2026-001');
  const orderId = order ? idOf(order) : null;
  const pos = (await nc.listRows(TID('positions'))).find(
    (p) => String(p['Позиция'] || '').startsWith('ПЗ-2026-001') && String(p['№ позиции']) === '1.0');
  const posId = pos ? idOf(pos) : null;

  // --- Ф.3 входной контроль ---
  const inc = await nc.listRows(TID('incoming_control'));
  if (!inc.some((r) => String(r['Поставщик'] || '').includes('(демо)'))) {
    const rec = await nc.createRow(TID('incoming_control'), {
      'Дата': '2026-04-15', 'Поставщик': 'ООО «Бронзалит» (демо)', 'Накладная №': 'РН-1042', 'Накладная от': '2026-04-14',
      'Договор / Заказ №': 'ПЗ-2026-001', 'Наименование материала': 'Труба бронзовая БрАЖ9-4',
      'Марка / Сортамент': 'БрАЖ9-4, Ø60×10', 'Кол-во': 12, 'Ед. изм.': 'м', 'Дата изготовления': '2026-03-01',
      'Документы': 'Сертификат качества,Накладная', 'Заключение': 'ГОДЕН',
      'Контролёр ОТК': 'Сидоров А.А.', 'Представитель склада': 'Кузнецова О.П.', 'Получатель': 'Мастер УЧ-16',
    });
    if (orderId) await nc.linkRecords(TID('orders'), COL('orders', 'Входной контроль'), orderId, [idOf(rec)]).catch(() => {});
    log('+ Ф.3 входной контроль (демо)');
  } else log('Ф.3: демо уже есть — пропуск');

  // --- Ф.4 приёмочный контроль ---
  const acc = await nc.listRows(TID('acceptance_control'));
  if (!acc.some((r) => String(r['Партия / серия'] || '').includes('(демо)'))) {
    const rec = await nc.createRow(TID('acceptance_control'), {
      'Дата': '2026-04-28', 'Заказ №': 'ПЗ-2026-001', 'МК №': 'МК-КОМ-2026-001',
      'Наименование изделия': 'Втулка биметаллическая', 'Чертёж №': '23.12.08.021', 'Кол-во, шт.': 4,
      'Партия / серия': 'ПАРТ-2026-007 (демо)', 'Внешний вид': 'Соответствует', 'Маркировка': 'Нанесена',
      'Комплектность': 'Полная', 'МК подписана': 'Все операции', 'Заключение': 'ГОДЕН',
      'Контролёр ОТК': 'Сидоров А.А.', 'Директор по производству': 'Петров В.И.',
    });
    if (posId) await nc.linkRecords(TID('positions'), COL('positions', 'Приёмочный контроль'), posId, [idOf(rec)]).catch(() => {});
    log('+ Ф.4 приёмочный контроль (демо)');
  } else log('Ф.4: демо уже есть — пропуск');

  // --- Ф.5 акт о несоответствии ---
  const nco = await nc.listRows(TID('nonconformity'));
  if (!nco.some((r) => String(r['Участок / Обнаружил'] || '').includes('(демо)'))) {
    const rec = await nc.createRow(TID('nonconformity'), {
      'Дата': '2026-04-22', 'Этап обнаружения': 'Операционный', 'Заказ № / МК №': 'ПЗ-2026-001 / МК-КОМ-2026-001',
      'Наименование изделия / материала': 'Втулка биметаллическая', 'Кол-во НП': 1, 'Участок / Обнаружил': 'УЧ-10 / Сидоров (демо)',
      'Описание несоответствия': 'Занижен наружный диаметр на 0,15 мм вне поля допуска (операция токарная).',
      'Причина (предварительная)': 'Износ резца, не проконтролирован размер при переустановке.',
      'Решение': 'Исправить (доработка)', 'Согласование заказчика': 'Не требуется',
      'Решение принял': 'Петров В.И.', 'Дата решения': '2026-04-22',
      'Корректирующее действие (ДП–У.2)': 'Заменить резец, добавить контрольный замер после переустановки в РИ.',
      'Срок': '2026-04-25', 'Ответственный': 'Мастер УЧ-10',
      'Результативность': 'Эффективно', 'Дата проверки': '2026-04-26', 'Результат проверки': 'Размер в допуске, повторов нет.',
      'Составил': 'Сидоров А.А.', 'Согласовал (ДпП)': 'Петров В.И.',
    });
    if (orderId) await nc.linkRecords(TID('orders'), COL('orders', 'Несоответствия'), orderId, [idOf(rec)]).catch(() => {});
    log('+ Ф.5 акт о несоответствии (демо)');
  } else log('Ф.5: демо уже есть — пропуск');

  console.log('\n✓ Демо контроля готово. Далее: assign-control-number, затем печать render-control.mjs ВК-2026-001 / ПК-2026-001 / НП-2026-001');
}

main().catch((e) => { console.error('✗ Ошибка:', e.message); process.exit(1); });
